//! Envoi d'alertes e-mail via l'API Resend (https://resend.com).

use crate::langue::t;

use serde::Serialize;

#[derive(Serialize)]
struct ResendPayload {
    from: String,
    to: Vec<String>,
    subject: String,
    html: String,
}

pub struct AlerteEmail<'a> {
    pub nom_affaire: &'a str,
    pub juridiction: &'a str,
    pub numero_rg: &'a str,
    pub acte: &'a str,
    pub date_limite: &'a str,
    pub jours_restants: i64,
    pub fondement: &'a str,
    pub sanction: &'a str,
}

fn echapper(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;").replace('"', "&quot;")
}

pub fn valider_configuration(api_key: &str, destinataires: &[String]) -> Result<Vec<String>, String> {
    if api_key.trim().is_empty() {
        return Err(t("Clé API Resend non configurée (Paramètres > Alertes e-mail).").to_string());
    }
    let liste: Vec<String> = destinataires
        .iter()
        .map(|e| e.trim().to_string())
        .filter(|e| !e.is_empty())
        .collect();
    if liste.is_empty() {
        return Err(t("Aucun destinataire configuré (Paramètres > Alertes e-mail).").to_string());
    }
    if let Some(invalide) = liste.iter().find(|e| !e.contains('@') || e.contains(' ')) {
        return Err(crate::tr!("Adresse e-mail invalide : {}", "Invalid e-mail address: {}", invalide));
    }
    Ok(liste)
}

pub async fn envoyer_alerte_resend(
    api_key: &str,
    expediteur: &str,
    destinataires: Vec<String>,
    alerte: &AlerteEmail<'_>,
    est_test: bool,
) -> Result<String, String> {
    let liste = valider_configuration(api_key, &destinataires)?;
    let expediteur = if expediteur.trim().is_empty() {
        "Deadline Breaker <onboarding@resend.dev>".to_string()
    } else {
        expediteur.trim().to_string()
    };

    let sujet = if est_test {
        crate::langue::t("Deadline Breaker - E-mail de test des alertes").to_string()
    } else if alerte.jours_restants < 0 {
        crate::tr!("[DÉLAI EXPIRÉ] {} - {}", "[DEADLINE MISSED] {} - {}", alerte.nom_affaire, alerte.acte)
    } else {
        crate::tr!("[ALERTE J-{}] {} - {}", "[ALERT D-{}] {} - {}", alerte.jours_restants, alerte.nom_affaire, alerte.acte)
    };

    let html = format!(
        "<div style=\"font-family:Segoe UI,Arial,sans-serif;font-size:14px;color:#0f172a\">\
         <h2 style=\"color:#be123c;margin:0 0 12px\">{titre}</h2>\
         <table cellpadding=\"4\" style=\"border-collapse:collapse\">\
         <tr><td><b>Dossier</b></td><td>{nom}</td></tr>\
         <tr><td><b>Juridiction</b></td><td>{jur}</td></tr>\
         <tr><td><b>N° RG</b></td><td>{rg}</td></tr>\
         <tr><td><b>Acte / délai</b></td><td>{acte}</td></tr>\
         <tr><td><b>Échéance</b></td><td><b>{date}</b> ({reste})</td></tr>\
         <tr><td><b>Fondement</b></td><td>{fond}</td></tr>\
         <tr><td><b>Sanction</b></td><td>{sanction}</td></tr>\
         </table>\
         <p style=\"color:#64748b;font-size:12px;margin-top:16px\">{genere} \
         {verif}</p></div>",
        genere = if crate::langue::en() { "Alert generated by Deadline Breaker." } else { "Alerte générée par Deadline Breaker." },
        verif = if crate::langue::en() { "Always check the computation against the texts and the circumstances of the matter." } else { "Vérifiez toujours le calcul au regard des textes et des circonstances du dossier." },
        titre = match (est_test, crate::langue::en()) { (true, false) => "Test de la passerelle d'alertes", (true, true) => "Alert gateway test", (false, false) => "ALERTE PROCÉDURALE", (false, true) => "PROCEDURAL ALERT" },
        nom = echapper(alerte.nom_affaire),
        jur = echapper(alerte.juridiction),
        rg = echapper(alerte.numero_rg),
        acte = echapper(alerte.acte),
        date = echapper(alerte.date_limite),
        reste = if alerte.jours_restants < 0 {
            crate::tr!("expiré depuis {} j", "expired {} days ago", -alerte.jours_restants)
        } else {
            crate::tr!("reste {} j", "{} days left", alerte.jours_restants)
        },
        fond = echapper(alerte.fondement),
        sanction = echapper(alerte.sanction),
    );

    envoyer_html_sur(BASE_RESEND, api_key, &expediteur, liste, &sujet, &html).await
}

pub const BASE_RESEND: &str = "https://api.resend.com";

/// Envoi d'un e-mail HTML déjà rédigé (récapitulatif d'alertes automatiques).
pub async fn envoyer_html(api_key: &str, expediteur: &str, destinataires: Vec<String>, sujet: &str, html: &str) -> Result<String, String> {
    let liste = valider_configuration(api_key, &destinataires)?;
    let expediteur = if expediteur.trim().is_empty() { "Deadline Breaker <onboarding@resend.dev>" } else { expediteur.trim() };
    envoyer_html_sur(BASE_RESEND, api_key, expediteur, liste, sujet, html).await
}

pub async fn envoyer_html_sur(base: &str, api_key: &str, expediteur: &str, liste: Vec<String>, sujet: &str, html: &str) -> Result<String, String> {
    let payload = ResendPayload { from: expediteur.to_string(), to: liste.clone(), subject: sujet.to_string(), html: html.to_string() };

    let client = reqwest::Client::builder()
        .timeout(std::time::Duration::from_secs(20))
        .build()
        .map_err(|e| crate::tr!("Client HTTP indisponible : {}", "HTTP client unavailable: {}", e))?;

    let rep = client
        .post(format!("{}/emails", base))
        .bearer_auth(api_key.trim())
        .json(&payload)
        .send()
        .await
        .map_err(|e| crate::tr!("Erreur réseau Resend : {}", "Resend network error: {}", e))?;

    let statut = rep.status();
    if statut.is_success() {
        Ok(crate::tr!("E-mail transmis à Resend pour {} destinataire(s) : {}", "E-mail handed to Resend for {} recipient(s): {}", liste.len(), liste.join(", ")))
    } else {
        let corps = rep.text().await.unwrap_or_default();
        Err(crate::tr!("Erreur API Resend ({}) : {}", "Resend API error ({}): {}", statut.as_u16(), corps))
    }
}
